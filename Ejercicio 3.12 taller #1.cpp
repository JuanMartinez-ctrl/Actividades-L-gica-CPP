#include <iostream>

using namespace std;

int main() 
{
    int numeroEntero = 10;
    float numeroDecimal = 3.1416;
    char letra = 'A';

    cout << "Salida continua:" << endl;
    cout << "Texto " << numeroEntero << " " << numeroDecimal << " " << letra << endl << endl;

    cout << "Salida con saltos de linea:" << endl;
    cout << "Entero: " << numeroEntero << endl;
    cout << "Decimal: " << numeroDecimal << endl;
    cout << "Letra: " << letra << endl << endl;

    cout << "Salida con espacios simples:" << endl;
    cout << "ID: " << numeroEntero << " Valor: " << numeroDecimal << " Letra: " << letra << endl;


}